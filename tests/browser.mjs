  await page.locator('#policy-apps').fill('code.exe, zoom.exe');
  await page.locator('#policy-phase-apps').fill('otter.exe');
  await page.locator('#policy-displays').fill('2');
  await page.locator('#policy-context').fill('Captions agreed. <script>alert(1)</script>');
  await page.locator('#policy-accepted').check();
  await page.screenshot({path:'output/policy-preview.png',fullPage:true});
  await page.getByRole('button',{name:'Save agreed rules'}).click();
  await page.locator('#policy-dialog').waitFor({state:'hidden'});
  await page.locator('#start').click();
  check((await page.locator('#consent-policy-summary').textContent()).includes('otter.exe'),'Session rules missing from consent');
  for(const scope of ['windows','displays','gaze','audio_devices','extensions','remote_sessions'])await page.locator(`input[name=${scope}]`).uncheck();
  await page.locator('input[name=processes]').check();
  await page.locator('#accepted').check();await page.getByRole('button',{name:'Start selected checks'}).click();
