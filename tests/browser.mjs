  check(await page.locator('#policy-summary script').count()===0,'Policy context must be escaped');
  await page.locator('#policy-btn').click();
  await page.locator('#policy-phase').selectOption('discussion');
  await page.locator('#policy-accepted').check();
  await page.getByRole('button',{name:'Save agreed rules'}).click();
  await page.locator('#policy-dialog').waitFor({state:'hidden'});
  check((await page.locator('#policy-summary').textContent()).includes('Phase: discussion'),'Policy update not rendered');
  await page.locator('#stop').click();
  await page.waitForFunction(()=>document.querySelector('#session-status').textContent==='Session ended');
  const pdfWait=page.waitForEvent('download');await page.locator('#export-pdf').click();const pdf=await pdfWait;
  check(pdf.suggestedFilename().endsWith('.pdf'),'PDF export failed');
  const jsonWait=page.waitForEvent('download');await page.locator('#export-json').click();const audit=await jsonWait;
  check(audit.suggestedFilename().endsWith('.json'),'JSON export failed');
  const policyBundle=JSON.parse(await readFile(await audit.path(),'utf8'));
  const policies=policyBundle.events.map(e=>JSON.parse(e.payload_json)).filter(e=>e.kind==='session_policy');
  check(policies.length===2&&policies[0].data.phase==='coding'&&policies[1].data.phase==='discussion','Policy revisions missing from audit');
  check(policies.every(e=>e.data.approval_status==='unverified'),'Candidate policy must remain unverified');
