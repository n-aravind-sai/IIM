  await page.locator('#session').fill('test-session');
  await page.locator('#browser').fill('Chromium');
  await page.locator('#profile').fill('Interview');
  const inventoryDownload=page.waitForEvent('download');await page.locator('#export').click();
  const inventoryExport=JSON.parse(await readFile(await (await inventoryDownload).path(),'utf8'));
  check(inventoryExport.format==='iim.extensions.v3'&&inventoryExport.session_id==='test-session','Companion scope binding missing');
  check(inventoryExport.extensions[0].name==='Interview captions','Reviewed entries missing');
  await page.evaluate(()=>{chrome.management.getAll=async()=>{throw Error('denied');};});
  await page.locator('#review').click();
  check(await page.locator('#export').isDisabled(),'Failed review must invalidate the prior export');
