  await page.waitForFunction(()=>document.querySelector('#session-status').textContent==='Awaiting consent');
  // An extension-only session has a real, hardware-free gap until an inventory arrives.
  await page.locator('[data-view=live]').click();
  await page.locator('#start').click();
  for(const scope of ['windows','displays','gaze','audio_devices','processes','remote_sessions'])await page.locator(`input[name=${scope}]`).uncheck();
  await page.locator('input[name=extensions]').check();await page.locator('#accepted').check();
  await page.getByRole('button',{name:'Start selected checks'}).click();
  await page.locator('#coverage-gap-notice').waitFor({state:'visible'});
  check((await page.locator('#coverage-gap-notice').textContent()).includes('Browser extensions'),'Missing coverage gap explanation');
  await page.locator('[data-view=privacy]').click();
  await page.locator('#extension-file').setInputFiles({name:'fixture-inventory.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(await exportInventory([],{session_id:await page.locator('#inventory-session').inputValue(),browser:'Chromium',profile:'Test'})))});
  await page.locator('[data-view=live]').click();
  await page.locator('#coverage-gap-notice').waitFor({state:'hidden'});
  await page.locator('#stop').click();
  await page.waitForFunction(()=>document.querySelector('#session-status').textContent==='Session ended');
  const gapDownload=page.waitForEvent('download');await page.locator('#export-json').click();
  const gapBundle=JSON.parse(await readFile(await (await gapDownload).path(),'utf8'));
  const gapEvents=gapBundle.events.map(e=>JSON.parse(e.payload_json));
  check(gapEvents.some(e=>e.kind==='coverage_gap_opened'),'Gap missing from signed export');
  check(gapEvents.some(e=>e.kind==='coverage_gap_closed'&&e.data.end_reason==='measurements_resumed'),'Recovery missing from signed export');
  check(gapEvents.every(e=>e.event_id&&e.run_id),'Versioned event identity missing');
  await page.locator('[data-view=privacy]').click();page.once('dialog',dialog=>dialog.accept());await page.locator('#delete').click();
