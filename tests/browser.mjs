  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile horizontal overflow');
  // Exercise the actual companion UI with a fixture management API; no real profile is inspected.
  await page.route('**/companion/*', async route=>{
    const name=new URL(route.request().url()).pathname.split('/').pop();
    if(!['popup.html','popup.js','popup.css','inventory.js'].includes(name))return route.abort();
    await route.fulfill({body:await readFile(`companion/${name}`),contentType:name.endsWith('.js')?'text/javascript':name.endsWith('.css')?'text/css':'text/html'});
  });
  await page.addInitScript(()=>{globalThis.chrome={runtime:{id:'fixture'},management:{getAll:async()=>[
    {id:'one',type:'extension',name:'Interview captions',enabled:true}
  ]}};});
